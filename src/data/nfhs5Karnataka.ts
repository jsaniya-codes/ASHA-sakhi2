export function getDistrictCoords(districtName: string): { lat: number; lng: number } {
  const match = KARNATAKA_DISTRICTS.find(
    (d) => d.district.toLowerCase() === districtName.trim().toLowerCase()
  );
  if (match) {
    return { lat: match.lat, lng: match.lng };
  }
  return { lat: 15.3173, lng: 75.7139 };
}
